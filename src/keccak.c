/* Keccak-f[1600] and Keccak-256 (the original padding, 0x01, as Ethereum uses). */

#include "zkvm.h"

static const uint64_t RoundConstants[24] = {
    0x0000000000000001ULL, 0x0000000000008082ULL, 0x800000000000808aULL, 0x8000000080008000ULL,
    0x000000000000808bULL, 0x0000000080000001ULL, 0x8000000080008081ULL, 0x8000000000008009ULL,
    0x000000000000008aULL, 0x0000000000000088ULL, 0x0000000080008009ULL, 0x000000008000000aULL,
    0x000000008000808bULL, 0x800000000000008bULL, 0x8000000000008089ULL, 0x8000000000008003ULL,
    0x8000000000008002ULL, 0x8000000000000080ULL, 0x000000000000800aULL, 0x800000008000000aULL,
    0x8000000080008081ULL, 0x8000000000008080ULL, 0x0000000080000001ULL, 0x8000000080008008ULL,
};

#define ROL(v, n) (((v) << (n)) | ((v) >> (64 - (n))))

/* One round body unrolled over named lanes (lane i = x + 5y), the round loop kept: with no rotate
 * instruction and 32-bit registers, indexed loops over the state cost several times the work.
 * The permutation where the platform has no Keccak delegation (keccak_f1600 is the platform's). */
void keccak_f1600_soft(uint64_t s[25])
{
    uint64_t a00 = s[0], a01 = s[1], a02 = s[2], a03 = s[3], a04 = s[4];
    uint64_t a05 = s[5], a06 = s[6], a07 = s[7], a08 = s[8], a09 = s[9];
    uint64_t a10 = s[10], a11 = s[11], a12 = s[12], a13 = s[13], a14 = s[14];
    uint64_t a15 = s[15], a16 = s[16], a17 = s[17], a18 = s[18], a19 = s[19];
    uint64_t a20 = s[20], a21 = s[21], a22 = s[22], a23 = s[23], a24 = s[24];
    uint64_t b00, b01, b02, b03, b04, b05, b06, b07, b08, b09, b10, b11, b12;
    uint64_t b13, b14, b15, b16, b17, b18, b19, b20, b21, b22, b23, b24;
    uint64_t c0, c1, c2, c3, c4, d;

    for (int round = 0; round < 24; round++)
    {
        /* GENERATED by tests/gen_keccak.py */
        c0 = a00 ^ a05 ^ a10 ^ a15 ^ a20;
        c1 = a01 ^ a06 ^ a11 ^ a16 ^ a21;
        c2 = a02 ^ a07 ^ a12 ^ a17 ^ a22;
        c3 = a03 ^ a08 ^ a13 ^ a18 ^ a23;
        c4 = a04 ^ a09 ^ a14 ^ a19 ^ a24;
        d = c4 ^ ROL(c1, 1);
        a00 ^= d; a05 ^= d; a10 ^= d; a15 ^= d; a20 ^= d;
        d = c0 ^ ROL(c2, 1);
        a01 ^= d; a06 ^= d; a11 ^= d; a16 ^= d; a21 ^= d;
        d = c1 ^ ROL(c3, 1);
        a02 ^= d; a07 ^= d; a12 ^= d; a17 ^= d; a22 ^= d;
        d = c2 ^ ROL(c4, 1);
        a03 ^= d; a08 ^= d; a13 ^= d; a18 ^= d; a23 ^= d;
        d = c3 ^ ROL(c0, 1);
        a04 ^= d; a09 ^= d; a14 ^= d; a19 ^= d; a24 ^= d;
        b00 = a00;
        b10 = ROL(a01, 1);
        b20 = ROL(a02, 62);
        b05 = ROL(a03, 28);
        b15 = ROL(a04, 27);
        b16 = ROL(a05, 36);
        b01 = ROL(a06, 44);
        b11 = ROL(a07, 6);
        b21 = ROL(a08, 55);
        b06 = ROL(a09, 20);
        b07 = ROL(a10, 3);
        b17 = ROL(a11, 10);
        b02 = ROL(a12, 43);
        b12 = ROL(a13, 25);
        b22 = ROL(a14, 39);
        b23 = ROL(a15, 41);
        b08 = ROL(a16, 45);
        b18 = ROL(a17, 15);
        b03 = ROL(a18, 21);
        b13 = ROL(a19, 8);
        b14 = ROL(a20, 18);
        b24 = ROL(a21, 2);
        b09 = ROL(a22, 61);
        b19 = ROL(a23, 56);
        b04 = ROL(a24, 14);
        a00 = b00 ^ (~b01 & b02);
        a01 = b01 ^ (~b02 & b03);
        a02 = b02 ^ (~b03 & b04);
        a03 = b03 ^ (~b04 & b00);
        a04 = b04 ^ (~b00 & b01);
        a05 = b05 ^ (~b06 & b07);
        a06 = b06 ^ (~b07 & b08);
        a07 = b07 ^ (~b08 & b09);
        a08 = b08 ^ (~b09 & b05);
        a09 = b09 ^ (~b05 & b06);
        a10 = b10 ^ (~b11 & b12);
        a11 = b11 ^ (~b12 & b13);
        a12 = b12 ^ (~b13 & b14);
        a13 = b13 ^ (~b14 & b10);
        a14 = b14 ^ (~b10 & b11);
        a15 = b15 ^ (~b16 & b17);
        a16 = b16 ^ (~b17 & b18);
        a17 = b17 ^ (~b18 & b19);
        a18 = b18 ^ (~b19 & b15);
        a19 = b19 ^ (~b15 & b16);
        a20 = b20 ^ (~b21 & b22);
        a21 = b21 ^ (~b22 & b23);
        a22 = b22 ^ (~b23 & b24);
        a23 = b23 ^ (~b24 & b20);
        a24 = b24 ^ (~b20 & b21);
        a00 ^= RoundConstants[round];
        /* END GENERATED */
    }

    s[0] = a00, s[1] = a01, s[2] = a02, s[3] = a03, s[4] = a04;
    s[5] = a05, s[6] = a06, s[7] = a07, s[8] = a08, s[9] = a09;
    s[10] = a10, s[11] = a11, s[12] = a12, s[13] = a13, s[14] = a14;
    s[15] = a15, s[16] = a16, s[17] = a17, s[18] = a18, s[19] = a19;
    s[20] = a20, s[21] = a21, s[22] = a22, s[23] = a23, s[24] = a24;
}

/* The ZisK-named permutation entry the managed Keccak reaches in zkVM builds. */
void syscall_keccak_f(uint64_t state[25])
{
    keccak_f1600(state);
}

zkvm_status zkvm_keccak256(const uint8_t *data, size_t len, uint8_t output[32])
{
#ifdef AIRBENDER
    airbender_keccak256(data, len, output);
    return ZKVM_EOK;
#else
    enum { Rate = 136 };
    uint64_t state[25] = {0};
    uint8_t block[Rate];

    for (;;)
    {
        size_t take = len < Rate ? len : Rate;
        memcpy(block, data, take);
        if (take < Rate)
        {
            memset(block + take, 0, Rate - take);
            block[take] ^= 0x01;
            block[Rate - 1] ^= 0x80;
        }
        for (int i = 0; i < Rate / 8; i++)
        {
            uint64_t lane = 0;
            for (int b = 7; b >= 0; b--)
                lane = (lane << 8) | block[i * 8 + b];
            state[i] ^= lane;
        }
        keccak_f1600(state);
        if (take < Rate)
            break;
        data += Rate;
        len -= Rate;
    }

    for (int i = 0; i < 4; i++)
        for (int b = 0; b < 8; b++)
            output[i * 8 + b] = (uint8_t)(state[i] >> (8 * b));
    return ZKVM_EOK;
#endif
}

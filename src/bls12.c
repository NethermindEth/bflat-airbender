static int be_cmp(const uint8_t *a, const uint8_t *b, size_t n)
{
    for (size_t i = 0; i < n; i++)
        if (a[i] != b[i])
            return a[i] < b[i] ? -1 : 1;
    return 0;
}

/*
 * A compressed G1 point (ZCash encoding): flag bits compressed (0x80, required), infinity (0x40,
 * then everything else zero) and sign (0x20, set for the larger of y and p - y) over a 381-bit x.
 */
static bool g1_uncompress(point *p, const uint8_t in[48])
{
    uint8_t buf[FpBytes], neg[FpBytes];
    memset(p, 0, sizeof(*p));
    if (!(in[0] & 0x80))
        return false;
    if (in[0] & 0x40)
    {
        buf[0] = 0xc0;
        memset(buf + 1, 0, FpBytes - 1);
        return be_cmp(in, buf, FpBytes) == 0;
    }
    memcpy(buf, in, FpBytes);
    buf[0] &= 0x1f;
    if (!fp_from_be(&p->x.c[0], buf))
        return false;
    fp2 rhs, n;
    fq_mul(&rhs, &p->x, &p->x, 1);
    fq_mul(&rhs, &rhs, &p->x, 1);
    fq_add(&rhs, &rhs, &C->b1, 1);
    if (!fq_sqrt(&p->y, &rhs, 1))
        return false;
    fq_neg(&n, &p->y, 1);
    fp_to_be(buf, &p->y.c[0]);
    fp_to_be(neg, &n.c[0]);
    if ((be_cmp(buf, neg, FpBytes) > 0) != ((in[0] & 0x20) != 0))
        p->y = n;
    p->z.c[0] = C->one;
    return true;
}

zkvm_status zkvm_kzg_point_eval(const uint8_t commitment[48], const uint8_t z[32], const uint8_t y[32],
                                const uint8_t proof[48], bool *verified)
{
    ec_use(&Bls12);
    *verified = false;
    point c, pi, g, q, t;
    if (be_cmp(z, Order, ScalarBytes) >= 0 || be_cmp(y, Order, ScalarBytes) >= 0)
        return ZKVM_EOK;
    if (!g1_uncompress(&c, commitment) || !g1_in_group(&c) || !g1_uncompress(&pi, proof) || !g1_in_group(&pi))
        return ZKVM_EOK;

    /* e(C - [y]G1, -G2) e(proof, [tau - z]G2) == 1 */
    pt_load(&g, G1Gen, 1, false);
    pt_mul(&t, &g, y, ScalarBytes, 1);
    pt_neg(&t, &t, 1);
    pt_add(&c, &c, &t, 1);
    pt_load(&g, G2Gen, 2, false);
    pt_load(&q, TauG2, 2, false);
    pt_mul(&t, &g, z, ScalarBytes, 2);
    pt_neg(&t, &t, 2);
    pt_add(&q, &q, &t, 2);
    pt_neg(&g, &g, 2);

    fp12 f;
    fp12_one(&f);
    point g1s[2] = {c, pi}, g2s[2] = {g, q};
    pairing_add_batch(&f, g1s, g2s, 2);
    *verified = pairing_is_one(&f);
    return ZKVM_EOK;
}

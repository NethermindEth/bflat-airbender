enum
{
    FpBytes = 48,
    ScalarBytes = 32
};

/* A primitive cube root of unity: (x, y) -> (beta x, y) acts on G1 as multiplication by -x^2. */
static fp Beta = {{0x798a64e8, 0x30f1361b, 0x7ece5a2a, 0xf3b8ddab, 0xc61577f7, 0x16a8ca3a, 0x74fd029b, 0xc26a2ff8, 0x60701c6e, 0x3636b766, 0x241b6160, 0x051ba4ab}};

static bool g1_in_group(const point *p)
{
    point a, b;
    a = *p;
    fp_mul(&a.x.c[0], &a.x.c[0], &Beta);
    pt_mul_x(&b, p, 1);
    pt_mul_x(&b, &b, 1);
    pt_neg(&b, &b, 1);
    return pt_eq(&a, &b, 1);
}

/* psi, the Frobenius on the twist, acts on G2 as multiplication by x. */
static bool g2_in_group(const point *p)
{
    point a, b;
    pt_frob(&a, p, true);
    pt_mul_x(&b, p, 2);
    return pt_eq(&a, &b, 2);
}

static bool load(point *p, const uint8_t *in, int d, bool subgroup)
{
    if (!pt_load(p, in, d, false) || !pt_on_curve(p, d))
        return false;
    return !subgroup || (d == 1 ? g1_in_group(p) : g2_in_group(p));
}

static zkvm_status add(const uint8_t *p1, const uint8_t *p2, uint8_t *result, int d)
{
    ec_use(&Bls12);
    point a, b;
    if (!load(&a, p1, d, false) || !load(&b, p2, d, false))
        return ZKVM_EFAIL;
    pt_add(&a, &a, &b, d);
    pt_store(result, &a, d, false);
    return ZKVM_EOK;
}

zkvm_status zkvm_bls12_g1_add(const uint8_t p1[96], const uint8_t p2[96], uint8_t result[96])
{
    return add(p1, p2, result, 1);
}

zkvm_status zkvm_bls12_g2_add(const uint8_t p1[192], const uint8_t p2[192], uint8_t result[192])
{
    return add(p1, p2, result, 2);
}

/* sum k_i P_i over pairs of a point and a scalar; no pairs gives the point at infinity. */
static zkvm_status msm(const uint8_t *pairs, size_t num_pairs, uint8_t *result, int d)
{
    ec_use(&Bls12);
    size_t stride = 2 * d * FpBytes + ScalarBytes;
    point p, acc;
    for (size_t i = 0; i < num_pairs; i++)
        if (!load(&p, pairs + i * stride, d, true))
            return ZKVM_EFAIL;

    memset(&acc, 0, sizeof(acc));
    for (int bit = 8 * ScalarBytes - 1; bit >= 0; bit--)
    {
        pt_dbl(&acc, &acc, d);
        for (size_t i = 0; i < num_pairs; i++)
        {
            const uint8_t *in = pairs + i * stride;
            if ((in[stride - 1 - bit / 8] >> (bit % 8)) & 1)
            {
                pt_load(&p, in, d, false);
                pt_add(&acc, &acc, &p, d);
            }
        }
    }
    pt_store(result, &acc, d, false);
    return ZKVM_EOK;
}

zkvm_status zkvm_bls12_g1_msm(const uint8_t *pairs, size_t num_pairs, uint8_t result[96])
{
    return msm(pairs, num_pairs, result, 1);
}

zkvm_status zkvm_bls12_g2_msm(const uint8_t *pairs, size_t num_pairs, uint8_t result[192])
{
    return msm(pairs, num_pairs, result, 2);
}

/* Each pair is a G1 point (96 bytes) then a G2 point (192 bytes). No pairs is a passing check. */
zkvm_status zkvm_bls12_pairing(const uint8_t *pairs, size_t num_pairs, bool *verified)
{
    ec_use(&Bls12);
    fp12 f;
    fp12_one(&f);
    *verified = false;
    for (size_t i = 0; i < num_pairs; i += PairingBatch)
    {
        point p[PairingBatch], q[PairingBatch];
        int count = num_pairs - i < PairingBatch ? (int)(num_pairs - i) : PairingBatch;
        for (int j = 0; j < count; j++)
        {
            const uint8_t *in = pairs + 288 * (i + j);
            if (!load(&p[j], in, 1, true) || !load(&q[j], in + 96, 2, true))
                return ZKVM_EFAIL;
        }
        pairing_add_batch(&f, p, q, count);
    }
    *verified = pairing_is_one(&f);
    return ZKVM_EOK;
}


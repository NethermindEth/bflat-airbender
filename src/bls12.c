typedef struct
{
    const fp *abz;
    const fp *iso;
    uint8_t len[4]; /* coefficient counts of xnum, xden, ynum, yden */
} isogeny;

static const isogeny Maps[2] = {{SswuG1, IsoG1, {12, 11, 16, 16}}, {SswuG2, IsoG2, {4, 3, 4, 4}}};

/* The i-th degree-d constant of a table. */
static void coef(fp2 *r, const fp *table, int i, int d)
{
    memset(r, 0, sizeof(*r));
    memcpy(r->c, table + i * d, d * sizeof(fp));
}

/* sgn0 of RFC 9380: the parity of the first non-zero coordinate. */
static int sgn0(const fp2 *a, int d)
{
    fp t;
    fp_from_mont(&t, &a->c[0]);
    int sign = t.l[0] & 1;
    if (d == 2 && fp_is_zero(&t))
    {
        fp_from_mont(&t, &a->c[1]);
        sign = t.l[0] & 1;
    }
    return sign;
}

/* g(x) = x^3 + A x + B on the isogenous curve. */
static void sswu_g(fp2 *r, const fp2 *x, const fp2 *a, const fp2 *b, int d)
{
    fp2 t;
    fq_mul(&t, x, x, d);
    fq_add(&t, &t, a, d);
    fq_mul(&t, &t, x, d);
    fq_add(r, &t, b, d);
}

static void poly(fp2 *r, const fp *table, int len, const fp2 *x, int d)
{
    fp2 c;
    memset(r, 0, sizeof(*r));
    for (int i = len - 1; i >= 0; i--)
    {
        fq_mul(r, r, x, d);
        coef(&c, table, i, d);
        fq_add(r, r, &c, d);
    }
}

/* map_to_curve: the simplified SWU map (RFC 9380 section 6.6.2, not constant time) followed by
   the isogeny, as a Jacobian point; an exceptional input mapping to a zero denominator gives the point
   at infinity. */
static void map_to_curve(point *r, const fp2 *u, int d)
{
    const isogeny *m = &Maps[d - 1];
    fp2 a, b, z, t, tv, x, gx, y, one;
    coef(&a, m->abz, 0, d);
    coef(&b, m->abz, 1, d);
    coef(&z, m->abz, 2, d);
    memset(&one, 0, sizeof(one));
    one.c[0] = C->one;

    /* -b/a of each map, formed once: an inverse is an exponentiation. */
    static fp2 minus_b_over_a[2];
    static bool have_minus_b_over_a[2];
    if (!have_minus_b_over_a[d - 1])
    {
        fq_inv(&minus_b_over_a[d - 1], &a, d);
        fq_mul(&minus_b_over_a[d - 1], &minus_b_over_a[d - 1], &b, d);
        fq_neg(&minus_b_over_a[d - 1], &minus_b_over_a[d - 1], d);
        have_minus_b_over_a[d - 1] = true;
    }

    fq_mul(&t, u, u, d);
    fq_mul(&t, &t, &z, d);
    fq_mul(&tv, &t, &t, d);
    fq_add(&tv, &tv, &t, d);
    if (fq_is_zero(&tv, d))
    {
        fq_mul(&x, &z, &a, d);
        fq_inv(&x, &x, d);
        fq_mul(&x, &x, &b, d);
    }
    else
    {
        fq_inv(&tv, &tv, d);
        fq_add(&tv, &tv, &one, d);
        fq_mul(&x, &minus_b_over_a[d - 1], &tv, d);
    }
    sswu_g(&gx, &x, &a, &b, d);
    if (!fq_sqrt(&y, &gx, d))
    {
        fq_mul(&x, &x, &t, d);
        sswu_g(&gx, &x, &a, &b, d);
        fq_sqrt(&y, &gx, d);
    }
    if (sgn0(u, d) != sgn0(&y, d))
        fq_neg(&y, &y, d);

    /* The isogeny gives x = xn / xd and y = y yn / yd; with Z = xd yd that is the Jacobian point
       (xn xd yd^2, y yn xd^3 yd^2, Z), which no inverse forms. */
    fp2 xn, xd, yn, yd, yd2, xd3;
    const fp *k = m->iso;
    poly(&xn, k, m->len[0], &x, d);
    k += m->len[0] * d;
    poly(&xd, k, m->len[1], &x, d);
    k += m->len[1] * d;
    poly(&yn, k, m->len[2], &x, d);
    k += m->len[2] * d;
    poly(&yd, k, m->len[3], &x, d);
    fq_mul(&r->z, &xd, &yd, d);
    if (fq_is_zero(&r->z, d))
    {
        memset(r, 0, sizeof(*r));
        return;
    }
    fq_mul(&yd2, &yd, &yd, d);
    fq_mul(&r->x, &xn, &xd, d);
    fq_mul(&r->x, &r->x, &yd2, d);
    fq_mul(&xd3, &xd, &xd, d);
    fq_mul(&xd3, &xd3, &xd, d);
    fq_mul(&r->y, &y, &yn, d);
    fq_mul(&r->y, &r->y, &xd3, d);
    fq_mul(&r->y, &r->y, &yd2, d);
}

zkvm_status zkvm_bls12_map_fp_to_g1(const uint8_t field_element[48], uint8_t result[96])
{
    /* h_eff = 1 - x clears the G1 cofactor (RFC 9380 section 8.8.1). */
    static const uint8_t HEff[8] = {0xd2, 0x01, 0x00, 0x00, 0x00, 0x01, 0x00, 0x01};
    ec_use(&Bls12);
    fp2 u;
    point p;
    memset(&u, 0, sizeof(u));
    if (!fp_from_be(&u.c[0], field_element))
        return ZKVM_EFAIL;
    map_to_curve(&p, &u, 1);
    pt_mul(&p, &p, HEff, sizeof(HEff), 1);
    pt_store(result, &p, 1, false);
    return ZKVM_EOK;
}

/* h_eff P for G2 by the endomorphism of Budroni and Pintore (RFC 9380 appendix G.3). */
static void clear_cofactor_g2(point *r, const point *p)
{
    point t1, t2, t3;
    pt_mul_x(&t1, p, 2);
    pt_frob(&t2, p, true);
    pt_dbl(&t3, p, 2);
    pt_frob(&t3, &t3, true);
    pt_frob(&t3, &t3, true);
    pt_neg(&t2, &t2, 2);
    pt_add(&t3, &t3, &t2, 2);
    pt_neg(&t2, &t2, 2);
    pt_add(&t2, &t1, &t2, 2);
    pt_mul_x(&t2, &t2, 2);
    pt_add(&t3, &t3, &t2, 2);
    pt_neg(&t1, &t1, 2);
    pt_add(&t3, &t3, &t1, 2);
    pt_neg(&t1, p, 2);
    pt_add(r, &t3, &t1, 2);
}

zkvm_status zkvm_bls12_map_fp2_to_g2(const uint8_t field_element[96], uint8_t result[192])
{
    ec_use(&Bls12);
    fp2 u;
    point p;
    if (!fp_from_be(&u.c[0], field_element) || !fp_from_be(&u.c[1], field_element + FpBytes))
        return ZKVM_EFAIL;
    map_to_curve(&p, &u, 2);
    clear_cofactor_g2(&p, &p);
    pt_store(result, &p, 2, false);
    return ZKVM_EOK;
}


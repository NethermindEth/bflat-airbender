/*
 * BLS12-381 accelerators: the EIP-2537 operations and the EIP-4844 point evaluation, on the
 * shared arithmetic of ec.c.
 *
 * Points are EIP-2537's with the 16 zero bytes in front of every field element stripped: a G1
 * point is x || y (2 x 48 bytes), a G2 point x || y with each Fp2 element c0 || c1 (4 x 48 bytes),
 * and all zeros the point at infinity. A scalar is 32 bytes big-endian, any value. ZKVM_EFAIL
 * means invalid input, which fails the precompile: a field element not below p, a point off its
 * curve, or, for the multi-scalar multiplications and the pairing, a point outside the order-r
 * subgroup (EIP-2537 leaves addition without that check).
 *
 * Multi-scalar multiplication shares the doublings between the pairs and reads each point again
 * from the input when its bit is set, so it needs no buffer whatever the pair count. Subgroup
 * membership uses the endomorphism tests of Scott (ePrint 2021/1130, proven in 2022/352).
 */


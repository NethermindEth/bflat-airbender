"""Generates the unrolled Keccak-f[1600] round body in src/keccak.c (between the GENERATED markers).

Lane i = x + 5y. Theta, then rho+pi into b: b[y + 5*((2x+3y) % 5)] = rot(a[x+5y], R[x+5y]),
then chi and iota. Usage: gen_keccak.py <path to keccak.c>
"""
import re
import sys

R = [0, 1, 62, 28, 27, 36, 44, 6, 55, 20, 3, 10, 43, 25, 39, 41, 45, 15, 21, 8, 18, 2, 61, 56, 14]


def rot(v, n):
    return v if n == 0 else f"ROL({v}, {n})"


lines = []
for x in range(5):
    lines.append(f"c{x} = " + " ^ ".join(f"a{x + 5 * y:02d}" for y in range(5)) + ";")
for x in range(5):
    lines.append(f"d = c{(x + 4) % 5} ^ ROL(c{(x + 1) % 5}, 1);")
    lines.append(" ".join(f"a{x + 5 * y:02d} ^= d;" for y in range(5)))
for y in range(5):
    for x in range(5):
        i = x + 5 * y
        j = y + 5 * ((2 * x + 3 * y) % 5)
        lines.append(f"b{j:02d} = {rot(f'a{i:02d}', R[i])};")
for y in range(5):
    for x in range(5):
        lines.append(f"a{x + 5 * y:02d} = b{x + 5 * y:02d} ^ (~b{(x + 1) % 5 + 5 * y:02d} & b{(x + 2) % 5 + 5 * y:02d});")
lines.append("a00 ^= RoundConstants[round];")
body = "\n".join("        " + l for l in lines)

path = sys.argv[1]
src = open(path).read()
src = re.sub(r"(        /\* GENERATED by tests/gen_keccak\.py \*/\n).*?(        /\* END GENERATED \*/)",
             lambda m: m.group(1) + body + "\n" + m.group(2), src, flags=re.S)
open(path, "w").write(src)
print("ok")
